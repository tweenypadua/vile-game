// Builds supabase/seed.sql from supabase/data/*.json.
// Usage: node scripts/build-seed.mjs [launch-date]   (default 2026-10-24)
// Case #1 is published on the launch date, case #2 the next day, and so on.
import { readFileSync, writeFileSync } from "node:fs";

const launch = process.argv[2] || "2026-10-24";
const cases = JSON.parse(readFileSync("supabase/data/cases.json", "utf8"));
const decoys = JSON.parse(readFileSync("supabase/data/decoy-films.json", "utf8"));

// Must match src/lib/game.ts normalizeTitle().
function norm(s) {
  return String(s).toLowerCase().normalize("NFD").replace(/[̀-ͯ]/g, "")
    .replace(/&/g, " and ").replace(/[^a-z0-9 ]/g, " ").replace(/\s+/g, " ").trim()
    .replace(/ (19|20)\d\d$/, "").replace(/^(the|a|an) /, "");
}
const q = (s) => "'" + String(s).replace(/'/g, "''") + "'";
const day = (n) => {
  const d = new Date(launch + "T00:00:00Z");
  d.setUTCDate(d.getUTCDate() + n);
  return d.toISOString().slice(0, 10);
};

let sql = `-- Generated by scripts/build-seed.mjs. Launch date ${launch}.\n-- Answers get popularity 50 and decoys 10 so autocomplete ranks well-known titles first.\nbegin;\n\n`;

sql += "insert into films (title, title_normalized, release_year, popularity) values\n";
const films = [
  ...cases.map((c) => [c.title, c.year, 50]),
  ...decoys.map((d) => [d.title, d.year, 10]),
];
sql += films.map(([t, y, p]) => `  (${q(t)}, ${q(norm(t))}, ${y}, ${p})`).join(",\n");
sql += "\non conflict (title_normalized, release_year) do nothing;\n\n";

for (const c of cases) {
  const film = `(select id from films where title_normalized = ${q(norm(c.title))} and release_year = ${c.year})`;
  for (const a of c.aliases) {
    sql += `insert into film_aliases (film_id, alias, alias_normalized) values (${film}, ${q(a)}, ${q(norm(a))}) on conflict do nothing;\n`;
  }
  sql += `insert into puzzles (puzzle_number, publish_date, film_id, state) values (${c.case_number}, ${q(day(c.case_number - 1))}, ${film}, 'scheduled') on conflict (puzzle_number) do nothing;\n`;
  sql += "insert into puzzle_clues (puzzle_id, position, kind, body) values\n";
  sql += c.clues
    .map((cl) => `  ((select id from puzzles where puzzle_number = ${c.case_number}), ${cl.position}, ${q(cl.kind)}, ${q(cl.body)})`)
    .join(",\n");
  sql += "\non conflict (puzzle_id, position) do nothing;\n\n";
}

sql += "commit;\n";
writeFileSync("supabase/seed.sql", sql);
console.log(`Wrote supabase/seed.sql: ${films.length} films, ${cases.length} puzzles from ${launch} to ${day(cases.length - 1)}.`);
